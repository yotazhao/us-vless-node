#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Pack a FLAT .zip (Dockerfile + entrypoint.sh + app.py at archive root) for
platforms that take an archive upload.

    python pack_zip.py --out dist/us-vless.zip --uuid <UUID> --path /ws-xxxx --name US-VLESS
"""
import argparse
import os
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
FILES = ["Dockerfile", "entrypoint.sh", "app.py"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "dist", "us-vless.zip"))
    ap.add_argument("--uuid", default="")
    ap.add_argument("--path", default="")
    ap.add_argument("--name", default="US-VLESS")
    a = ap.parse_args()

    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    missing = [f for f in FILES if not os.path.exists(os.path.join(HERE, f))]
    if missing:
        sys.exit("missing: %s" % missing)

    with zipfile.ZipFile(a.out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in FILES:
            with open(os.path.join(HERE, f), "rb") as fh:
                data = fh.read()
            if f == "Dockerfile" and a.uuid:
                # appended ENV wins over the image default -> stable identity
                # across restarts without relying on a brittle exact-match edit
                data += (
                    "\n# --- baked node identity (generated by pack_zip.py) ---\n"
                    'ENV UUID={u} \\\n    WS_PATH={p} \\\n    NODE_NAME="{n}"\n'
                ).format(u=a.uuid, p=a.path, n=a.name).encode()
            info = zipfile.ZipInfo(f)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if f.endswith(".sh") else 0o644) << 16
            z.writestr(info, data)

    print("wrote %s (%.1f KB)" % (a.out, os.path.getsize(a.out) / 1024.0))
    print("uuid=%s path=%s name=%s" % (a.uuid or "(random at boot)", a.path or "(random at boot)", a.name))


if __name__ == "__main__":
    main()
